def norm_to_gripper_raw(value):

    value = float(
        np.clip(
            value,
            0.0,
            1.0,
        )
    )

    return int(
        round(
            value * 255.0
        )
    )


def command_gripper(
    gripper,
    normalized_target,
    previous_raw,
):

    raw_target = norm_to_gripper_raw(
        normalized_target
    )

    if (
        previous_raw is None
        or abs(
            raw_target - previous_raw
        ) >= GRIPPER_MIN_CHANGE
    ):

        gripper.move(
            raw_target,
            GRIPPER_SPEED,
            GRIPPER_FORCE,
        )

        print(
            f" | gripper={normalized_target:.3f}"
            f" raw={raw_target}",
            end="",
        )

        return raw_target

    return previous_raw


