# PREPARE / CLAMP POLICY TRAJECTORY
# ============================================================

def prepare_policy_chunk(
    actions,
    q_now,
):

    q_now = np.asarray(
        q_now,
        dtype=np.float64,
    )


    # ========================================================
    # Hard validity checks
    #
    # Invalid policy output should still terminate because
    # continuing from corrupt data is not useful.
    # ========================================================

    if actions.shape != (
        ACTION_HORIZON,
        7,
    ):

        raise RuntimeError(
            f"Expected "
            f"({ACTION_HORIZON}, 7), "
            f"got {actions.shape}"
        )


    if not np.all(
        np.isfinite(actions)
    ):

        raise RuntimeError(
            "Policy returned NaN or Inf"
        )


    # ========================================================
    # Select chunk
    # ========================================================

    raw_chunk = actions[
        :EXECUTE_ACTIONS
    ].copy()

    raw_joints = (
        raw_chunk[:, :6]
    )

    gripper_actions = np.clip(
        raw_chunk[:, 6],
        0.0,
        1.0,
    )


    # ========================================================
    # Diagnostics BEFORE clamping
    # ========================================================

    raw_first_delta = float(
        np.max(
            np.abs(
                raw_joints[0]
                - q_now
            )
        )
    )


    if EXECUTE_ACTIONS > 1:

        raw_step_delta = float(
            np.max(
                np.abs(
                    np.diff(
                        raw_joints,
                        axis=0,
                    )
                )
            )
        )

    else:

        raw_step_delta = 0.0


    raw_chunk_delta = float(
        np.max(
            np.abs(
                raw_joints
                - q_now
            )
        )
    )


    full_horizon_delta = float(
        np.max(
            np.abs(
                actions[:, :6]
                - q_now
            )
        )
    )


    # ========================================================
    # SAFE TRAJECTORY
    # ========================================================

    safe_joints = np.zeros_like(
        raw_joints
    )


    # --------------------------------------------------------
    # ACTION 0
    #
    # Limit first policy target relative to current actual
    # robot position.
    # --------------------------------------------------------

    safe_joints[0] = np.clip(
        raw_joints[0],
        q_now - MAX_FIRST_DELTA,
        q_now + MAX_FIRST_DELTA,
    )


    # --------------------------------------------------------
    # ACTIONS 1 ... N
    # --------------------------------------------------------

    for i in range(
        1,
        EXECUTE_ACTIONS,
    ):

        # Limit total displacement from observed position
        absolute_limited = np.clip(
            raw_joints[i],
            q_now - MAX_CHUNK_DELTA,
            q_now + MAX_CHUNK_DELTA,
        )


        # Limit action-to-action jump
        safe_joints[i] = np.clip(
            absolute_limited,
            safe_joints[i - 1]
            - MAX_STEP_DELTA,
            safe_joints[i - 1]
            + MAX_STEP_DELTA,
        )


        # Guarantee total chunk boundary
        safe_joints[i] = np.clip(
            safe_joints[i],
            q_now - MAX_CHUNK_DELTA,
            q_now + MAX_CHUNK_DELTA,
        )


    # ========================================================
    # Diagnostics AFTER clamping
    # ========================================================

    safe_first_delta = float(
        np.max(
            np.abs(
                safe_joints[0]
                - q_now
            )
        )
    )


    if EXECUTE_ACTIONS > 1:

        safe_step_delta = float(
            np.max(
                np.abs(
                    np.diff(
                        safe_joints,
                        axis=0,
                    )
                )
            )
        )

    else:

        safe_step_delta = 0.0


    safe_chunk_delta = float(
        np.max(
            np.abs(
                safe_joints
                - q_now
            )
        )
    )


    changed = np.any(
        np.abs(
            safe_joints
            - raw_joints
        ) > 1e-8,
        axis=1,
    )

    number_clamped = int(
        np.sum(changed)
    )


    # ========================================================
    # Print
    # ========================================================

    print(
        f"Raw first delta      : "
        f"{raw_first_delta:.5f} rad"
    )

    print(
        f"Raw step delta       : "
        f"{raw_step_delta:.5f} rad"
    )

    print(
        f"Raw {EXECUTE_ACTIONS} delta"
        f"      : "
        f"{raw_chunk_delta:.5f} rad"
    )

    print(
        f"Full horizon delta   : "
        f"{full_horizon_delta:.5f} rad"
    )


    if number_clamped:

        print(
            f"CLAMPED              : "
            f"{number_clamped}/"
            f"{EXECUTE_ACTIONS} actions"
        )

        print(
            f"Safe first delta     : "
            f"{safe_first_delta:.5f} rad"
        )

        print(
            f"Safe step delta      : "
            f"{safe_step_delta:.5f} rad"
        )

        print(
            f"Safe chunk delta     : "
            f"{safe_chunk_delta:.5f} rad"
        )

    else:

        print(
            "CLAMPED              : none"
        )


    print(
        f"Gripper next "
        f"{EXECUTE_ACTIONS}"
        f"      : "
        f"{np.min(gripper_actions):.3f}"
        f" -> "
        f"{np.max(gripper_actions):.3f}"
    )


    return (
        safe_joints,
        gripper_actions,
    )


# ============================================================
# PIECEWISE-LINEAR POLICY TRAJECTORY
# ============================================================

def build_linear_chunk_trajectory(
    q_start: np.ndarray,
    dq_start: np.ndarray,
    joint_actions: np.ndarray,
    dt_action: float = ACTION_DT,
    first_target_time: float = FIRST_TARGET_TIME,
):
    """
    Builds a piecewise-linear trajectory connecting the measured robot state at
    t=0 with the policy action targets. This matches the interpolation strategy
    used by maininferenceCode.py and cannot overshoot between target positions.

    Knots:
      t_0 = 0.0: q_start (with velocity dq_start)
      t_0 = first_target_time: joint_actions[0]
      t_k = first_target_time + k * dt_action: joint_actions[k], k in 1..N-1
      Total duration: first_target_time + (N - 1) * dt_action.

    Position is continuous. Nominal velocity is constant within each segment and
    nominal acceleration is zero; the CBF-QP enforces physical acceleration limits.
    """
    q_start = np.asarray(q_start, dtype=np.float64).reshape(6)
    np.asarray(dq_start, dtype=np.float64).reshape(6)  # Validate expected shape.
    joint_actions = np.asarray(joint_actions, dtype=np.float64)

    n_actions = len(joint_actions)
    if n_actions == 0:
        raise ValueError("joint_actions must contain at least one target")
    if first_target_time <= 0.0 or dt_action <= 0.0:
        raise ValueError("first_target_time and dt_action must be positive")

    action_times = first_target_time + np.arange(n_actions) * dt_action
    knot_times = np.concatenate(([0.0], action_times))
    chunk_duration = float(knot_times[-1])
    knot_positions = np.vstack([q_start, joint_actions])

    segment_durations = np.diff(knot_times)
    segment_velocities = np.diff(knot_positions, axis=0) / segment_durations[:, None]

    def segment_index(t):
        index = int(np.searchsorted(knot_times, t, side="right") - 1)
        return int(np.clip(index, 0, n_actions - 1))

    def trajectory_position(t):
        t_eval = float(np.clip(t, 0.0, chunk_duration))
        index = segment_index(t_eval)
        alpha = (t_eval - knot_times[index]) / segment_durations[index]
        alpha = float(np.clip(alpha, 0.0, 1.0))
        return knot_positions[index] + alpha * (
            knot_positions[index + 1] - knot_positions[index]
        )

    def trajectory_velocity(t):
        t_eval = float(np.clip(t, 0.0, chunk_duration))
        return segment_velocities[segment_index(t_eval)].copy()

    def trajectory_acceleration(t):
        del t
        return np.zeros(6, dtype=np.float64)

    return (
        trajectory_position,
        trajectory_velocity,
        trajectory_acceleration,
        chunk_duration,
    )


def get_spline_reference(
    trajectory_position,
    trajectory_velocity,
    trajectory_acceleration,
    tau: float,
    chunk_duration: float,
):
    """
    Evaluates nominal position, velocity, and acceleration from the spline at nominal time tau.
    """
    t_eval = float(np.clip(tau, 0.0, chunk_duration))
    nominal_q = trajectory_position(t_eval)
    nominal_Dq = trajectory_velocity(t_eval)
    nominal_DDq = trajectory_acceleration(t_eval)
    return nominal_q, nominal_Dq, nominal_DDq


