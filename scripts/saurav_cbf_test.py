def capture_and_infer(
    policy,
    rtde_r,
    gripper,
    front_cam,
    wrist_cam,
):

    # --------------------------------------------------------
    # Robot state
    # --------------------------------------------------------

    q_now = np.asarray(
        rtde_r.getActualQ(),
        dtype=np.float32,
    )

    gripper_raw = (
        gripper.get_current_position()
    )

    gripper_norm = (
        float(gripper_raw)
        / 255.0
    )

    state = np.concatenate(
        [
            q_now,
            [gripper_norm],
        ]
    ).astype(np.float32)


    # --------------------------------------------------------
    # Images
    # --------------------------------------------------------

    front_rgb = get_image(
        front_cam
    )

    wrist_rgb = get_image(
        wrist_cam
    )


    # --------------------------------------------------------
    # Policy input
    # --------------------------------------------------------

    observation = {
        "state": state,
        "base_rgb": front_rgb,
        "wrist_rgb": wrist_rgb,
        "prompt": PROMPT,
    }


    # --------------------------------------------------------
    # π0.5
    # --------------------------------------------------------

    result = policy.infer(
        observation
    )

    actions = np.asarray(
        result["actions"],
        dtype=np.float64,
    )

    return actions, q_now


