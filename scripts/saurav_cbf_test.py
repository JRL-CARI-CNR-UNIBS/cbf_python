def start_camera(serial):

    pipe = rs.pipeline()
    config = rs.config()

    config.enable_device(serial)

    config.enable_stream(
        rs.stream.color,
        CAM_W,
        CAM_H,
        rs.format.bgr8,
        CAM_FPS,
    )

    pipe.start(config)

    # Warm up camera
    for _ in range(10):
        pipe.wait_for_frames()

    return pipe


def get_image(pipe):

    frames = pipe.wait_for_frames()

    color = frames.get_color_frame()

    if not color:
        raise RuntimeError(
            "No camera frame received"
        )

    bgr = np.asanyarray(
        color.get_data()
    )

    rgb = cv2.cvtColor(
        bgr,
        cv2.COLOR_BGR2RGB,
    )

    rgb = image_tools.resize_with_pad(
        rgb,
        IMG_SIZE,
        IMG_SIZE,
    )

    return image_tools.convert_to_uint8(
        rgb
    )


