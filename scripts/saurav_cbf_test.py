class CrateSafetyFilter:
    """Detect when the TCP is below the bounded crate-opening plane."""

    def __init__(
        self,
        model,
        monitored_frame_ids,
        opening_points,
        entry_hysteresis,
        human_stop_distance,
    ):
        points = np.asarray(opening_points, dtype=np.float64)
        if points.shape != (4, 3) or not np.all(np.isfinite(points)):
            raise ValueError("CRATE_OPENING_POINTS must contain four finite XYZ points")

        self.model = model
        self.data = model.createData()
        self.monitored_frame_ids = [int(frame_id) for frame_id in monitored_frame_ids]
        self.p0 = points[0].copy()

        edge_u = points[1] - points[0]
        edge_v = points[3] - points[0]
        width = float(np.linalg.norm(edge_u))
        if width <= 1e-6 or float(np.linalg.norm(edge_v)) <= 1e-6:
            raise ValueError("Crate opening edges must have non-zero length")

        self.axis_u = edge_u / width
        edge_v_orthogonal = edge_v - np.dot(edge_v, self.axis_u) * self.axis_u
        height = float(np.linalg.norm(edge_v_orthogonal))
        if height <= 1e-6:
            raise ValueError("Crate opening points do not define a plane")
        self.axis_v = edge_v_orthogonal / height
        self.normal = np.cross(self.axis_u, self.axis_v)
        self.normal /= np.linalg.norm(self.normal)

        planarity_error = np.max(np.abs((points - self.p0) @ self.normal))
        if planarity_error > 0.01:
            raise ValueError(
                f"Crate opening points are not planar (max error {planarity_error:.4f} m)"
            )

        opposite_u = float(np.dot(points[2] - self.p0, self.axis_u))
        opposite_v = float(np.dot(points[2] - self.p0, self.axis_v))
        self.width = 0.5 * (width + opposite_u)
        self.height = 0.5 * (height + opposite_v)

        self.entry_hysteresis = float(entry_hysteresis)
        self.human_stop_distance = float(human_stop_distance)

    def monitored_positions(self, q):
        q = np.asarray(q, dtype=np.float64)
        pin.framesForwardKinematics(self.model, self.data, q)
        return np.vstack([
            self.data.oMf[frame_id].translation.copy()
            for frame_id in self.monitored_frame_ids
        ])

    def coordinates(self, position):
        relative = np.asarray(position, dtype=np.float64) - self.p0
        u = float(np.dot(relative, self.axis_u))
        v = float(np.dot(relative, self.axis_v))
        signed_height = float(np.dot(relative, self.normal))
        return u, v, signed_height

    def inside_opening(self, position):
        u, v, _ = self.coordinates(position)
        return (
            0.0 <= u <= self.width
            and 0.0 <= v <= self.height
        )

    def is_confined(self, position):
        _, _, signed_height = self.coordinates(position)
        depth = -signed_height
        return depth >= self.entry_hysteresis and self.inside_opening(position)

    def human_is_close(self, q, obstacle_positions):
        obstacles = np.asarray(obstacle_positions, dtype=np.float64)
        if obstacles.size == 0:
            return False, float("inf")
        obstacles = obstacles.reshape(-1, 3)
        robot_points = self.monitored_positions(q)
        differences = robot_points[:, None, :] - obstacles[None, :, :]
        distances = np.linalg.norm(differences, axis=2)
        minimum_distance = float(np.min(distances))
        return minimum_distance <= self.human_stop_distance, minimum_distance

