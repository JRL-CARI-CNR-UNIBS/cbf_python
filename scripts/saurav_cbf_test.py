# HIGH FREQUENCY INNER CONTROL LOOP (500 Hz)
# ============================================================

def execute_chunk_500hz(
    ctrl,
    crate_filter,
    bridge,
    rtde_c,
    rtde_r,
    gripper,
    spline,
    spline_vel,
    spline_acc,
    gripper_actions,
    chunk_duration: float,
    last_gripper_raw: int,
    max_wall_time_scale: float = 3.0,
):
    """
    Executes the 500 Hz B-CBF optimal control loop over the chunk spline.

    In nominal conditions, runs while nominal time tau (ctrl.trajectory_time) < chunk_duration (1.5s).

    Retriggering / replanning strategies:
    1. Nominal completion: tau >= chunk_duration (completed 1.5s chunk)
    2. Tracking error: max(|q_cmd - q_actual|) > REPLAN_TRACKING_ERROR (0.15 rad)
    3. Controller unfeasibility: out["unfeasible_cnt"] == "UNFEASIBLE"
    4. Obstacle stagnation: wall time > chunk_duration * max_wall_time_scale with scaling < 0.2
    """
    step_count = 0
    start_wall_time = time.perf_counter()
    replan_triggered = False
    replan_reason = "COMPLETED"

    max_tracking_err = 0.0
    worst_tracking_joint = 0
    h_min_overall = float("inf")
    d_min_overall = float("inf")
    scalings = []
    cbf_intervention_reported = False

    max_wall_time = chunk_duration * max_wall_time_scale

    try:
        while True:
            loop_start = time.perf_counter()
            wall_elapsed = loop_start - start_wall_time

            # ----------------------------------------------------
            # 1. Check Nominal Completion Condition
            # ----------------------------------------------------
            tau = ctrl.trajectory_time
            if tau >= chunk_duration:
                replan_triggered = False
                replan_reason = "COMPLETED"
                break

            # ----------------------------------------------------
            # 2. Check Obstacle Stagnation (Timeout) Retriggering
            # ----------------------------------------------------
            if wall_elapsed > max_wall_time and ctrl.Dtrajectory_time < 0.2:
                replan_triggered = True
                replan_reason = "OBSTACLE_STAGNATION"
                print(
                    f"\n[CBF Replan] Stagnation detected: wall time ({wall_elapsed:.2f}s) "
                    f"exceeded max allowed ({max_wall_time:.2f}s) with scale={ctrl.Dtrajectory_time:.3f}."
                )
                break

            # ----------------------------------------------------
            # 3. Synchronize RTDE control period (500 Hz = 0.002s)
            # ----------------------------------------------------
            period = None
            if rtde_c is not None:
                period = rtde_c.initPeriod()

            # ----------------------------------------------------
            # 4. Perception: Get Obstacles from Bridge
            # ----------------------------------------------------
            if bridge is not None:
                obs_pos, obs_vel, obs_acc = bridge.getObstacles()
            else:
                obs_pos = np.zeros((0, 3), dtype=np.float64)
                obs_vel = np.zeros((0, 3), dtype=np.float64)
                obs_acc = np.zeros((0, 3), dtype=np.float64)

            # ----------------------------------------------------
            # 5. Confined-space human stop (before the CBF step)
            # ----------------------------------------------------
            if crate_filter is not None:
                if rtde_r is not None:
                    tcp_position = np.asarray(
                        rtde_r.getActualTCPPose()[:3],
                        dtype=np.float64,
                    )
                else:
                    tcp_position = crate_filter.monitored_positions(ctrl.q)[0]

                confined = crate_filter.is_confined(tcp_position)
                if rtde_r is not None:
                    current_q = np.asarray(rtde_r.getActualQ(), dtype=np.float64)
                else:
                    current_q = ctrl.q.copy()
                human_close, human_distance = crate_filter.human_is_close(
                    current_q,
                    obs_pos,
                )
                if confined and human_close:
                    hold_q = current_q
                    if rtde_c is not None:
                        rtde_c.servoJ(
                            hold_q.tolist(),
                            0.0,
                            0.0,
                            SERVO_DT,
                            LOOKAHEAD_TIME,
                            GAIN,
                        )
                    replan_triggered = True
                    replan_reason = "CRATE_CONFINED_HUMAN"
                    print(
                        f"\n[Crate Filter] TCP confined and human distance "
                        f"{human_distance:.3f} m <= "
                        f"{crate_filter.human_stop_distance:.3f} m. Holding and replanning."
                    )
                    break

            # ----------------------------------------------------
            # 6. Query Spline Reference (C^2 continuous)
            # ----------------------------------------------------
            nominal_q, nominal_Dq, nominal_DDq = get_spline_reference(
                spline,
                spline_vel,
                spline_acc,
                tau,
                chunk_duration,
            )

            # ----------------------------------------------------
            # 7. Step B-CBF Optimal Controller
            # ----------------------------------------------------
            out = ctrl.step(
                obs_pos=obs_pos,
                obs_vel=obs_vel,
                obs_acc=obs_acc,
                nominal_q=nominal_q,
                nominal_Dq=nominal_Dq,
                nominal_DDq=nominal_DDq,
            )

            q_cmd = out["q"]
            dq_cmd = out["dq"]
            ddq_cmd = out["ddq"]
            new_tau = out["trajectory_time"]
            unfeasible_status = out["unfeasible_cnt"]
            scaling = out["Dtrajectory_time"]
            h_min = out["h_min"]
            d_min = out["d_min"]

            scalings.append(scaling)
            h_min_overall = min(h_min_overall, h_min)
            d_min_overall = min(d_min_overall, d_min)

            obstacle_count = int(obs_pos.shape[0])
            cbf_intervening = obstacle_count > 0 and (
                h_min <= CBF_WARNING_H_THRESHOLD
                or scaling <= CBF_SCALING_INTERVENTION_THRESHOLD
            )
            if cbf_intervening and not cbf_intervention_reported:
                print(
                    f"\n[CBF Triggered] h_min={h_min:.3f} m | "
                    f"d_min={d_min:.3f} m | scale={scaling:.3f}"
                )
                cbf_intervention_reported = True
            elif not cbf_intervening and cbf_intervention_reported:
                print(
                    f"\n[CBF Cleared] h_min={h_min:.3f} m | "
                    f"d_min={d_min:.3f} m | scale={scaling:.3f}"
                )
                cbf_intervention_reported = False

            # ----------------------------------------------------
            # 8. Actuation: Send Command to Robot
            # ----------------------------------------------------
            if rtde_c is not None:
                rtde_c.servoJ(
                    q_cmd.tolist(),
                    0.0,
                    0.0,
                    SERVO_DT,
                    LOOKAHEAD_TIME,
                    GAIN,
                )

            if bridge is not None:
                try:
                    bridge.sendCommand(q_cmd)
                except Exception:
                    pass

            # ----------------------------------------------------
            # 8. Gripper: Update based on chunk progress
            # ----------------------------------------------------
            if gripper is not None and len(gripper_actions) > 0:
                if tau < FIRST_TARGET_TIME:
                    action_idx = 0
                else:
                    action_idx = 1 + int(
                        (tau - FIRST_TARGET_TIME) / ACTION_DT
                    )
                action_idx = min(action_idx, len(gripper_actions) - 1)
                last_gripper_raw = command_gripper(
                    gripper,
                    gripper_actions[action_idx],
                    last_gripper_raw,
                )

            # ----------------------------------------------------
            # 9. Feedback & Tracking Error Diagnostics
            # ----------------------------------------------------
            if rtde_r is not None:
                q_actual = np.asarray(rtde_r.getActualQ(), dtype=np.float64)
            else:
                q_actual = q_cmd.copy()

            err_per_joint = np.abs(q_cmd - q_actual)
            tracking_error = float(np.max(err_per_joint))
            worst_joint = int(np.argmax(err_per_joint))

            if tracking_error > max_tracking_err:
                max_tracking_err = tracking_error
                worst_tracking_joint = worst_joint

            step_count += 1

            # Print status periodically (every 50 ms = 25 steps @ 500 Hz).
            # A 1e9 barrier value is an internal no-obstacle sentinel, so never
            # display it as a real measured distance.
            if step_count % 25 == 0:
                if obstacle_count:
                    proximity = f"d_min={d_min:.3f}m | h_min={h_min:.3f}m"
                else:
                    proximity = "d_min=N/A | h_min=N/A | PERCEPTION EMPTY"
                print(
                    f"\r[500Hz] tau={new_tau:5.2f}/{chunk_duration:.2f}s | "
                    f"CBF={'ON' if ctrl.useCbf else 'OFF'} | obs={obstacle_count} | "
                    f"scale={scaling:.3f} | {proximity} | "
                    f"err={tracking_error:.4f} rad (J{worst_joint + 1}) | "
                    f"{unfeasible_status}",
                    end="",
                    flush=True,
                )

            # ----------------------------------------------------
            # 10. Replan Retriggering Check: Tracking Error
            # ----------------------------------------------------
            if tracking_error > REPLAN_TRACKING_ERROR:
                replan_triggered = True
                replan_reason = "TRACKING_ERROR"
                print(
                    f"\n[CBF Replan] Tracking error ({tracking_error:.4f} rad, J{worst_joint + 1}) "
                    f"exceeded threshold ({REPLAN_TRACKING_ERROR:.4f} rad)."
                )
                break

            # ----------------------------------------------------
            # 11. Replan Retriggering Check: Unfeasible State
            # ----------------------------------------------------
            if unfeasible_status == "UNFEASIBLE":
                replan_triggered = True
                replan_reason = "UNFEASIBLE"
                print(
                    f"\n[CBF Replan] Controller triggered emergency deceleration (UNFEASIBLE QP)."
                )
                break

            # ----------------------------------------------------
            # 12. Period Sync (500 Hz)
            # ----------------------------------------------------
            if rtde_c is not None and period is not None:
                rtde_c.waitPeriod(period)
            else:
                elapsed_total = time.perf_counter() - loop_start
                rest = SERVO_DT - elapsed_total
                if rest > 0:
                    time.sleep(rest)

    except KeyboardInterrupt:
        replan_triggered = True
        replan_reason = "INTERRUPTED"
        raise

    finally:
        print()  # Newline after \r prints

    # Read final actual state
    if rtde_r is not None:
        q_final = np.asarray(rtde_r.getActualQ(), dtype=np.float64)
        try:
            dq_final = np.asarray(rtde_r.getActualQd(), dtype=np.float64)
        except Exception:
            dq_final = ctrl.dq.copy()
    else:
        q_final = ctrl.q.copy()
        dq_final = ctrl.dq.copy()

    stats = {
        "step_count": step_count,
        "max_tracking_err": max_tracking_err,
        "worst_joint": worst_tracking_joint,
        "h_min": h_min_overall,
        "d_min": d_min_overall,
        "mean_scaling": float(np.mean(scalings)) if scalings else 1.0,
        "wall_elapsed": time.perf_counter() - start_wall_time,
        "nominal_time": ctrl.trajectory_time,
    }

    return replan_triggered, replan_reason, q_final, dq_final, last_gripper_raw, stats


# ============================================================
# HOLD WHILE π0.5 IS RUNNING (500 Hz)
# ============================================================

def hold_while_inferencing(
    rtde_c,
    future,
    hold_target,
):
    hold_target = np.asarray(
        hold_target,
        dtype=np.float64,
    )

    while not future.done():
        if rtde_c is not None:
            period = rtde_c.initPeriod()
            rtde_c.servoJ(
                hold_target.tolist(),
                0.0,
                0.0,
                SERVO_DT,
                LOOKAHEAD_TIME,
                GAIN,
            )
            rtde_c.waitPeriod(period)
        else:
            time.sleep(SERVO_DT)


